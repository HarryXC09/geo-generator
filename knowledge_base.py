def get_product_context(product_id: str) -> str:
    """
    根据 product_id 查询产品数据，返回格式化 Markdown 上下文块。

    返回的字符串将被注入 System Prompt 的 <Product_Context> 标签中，
    作为 LLM 创作时必须严格依据的知识来源。
    """
    product = PETCARE_PRODUCTS.get(product_id)
    if not product:
        return ""

    return (
        "<Product_Context>\n"
        f"### 产品名称：{product['name']}\n\n"
        f"**核心原理**：{product['principle']}\n\n"
        f"**功能**：{product['functions']}\n\n"
        f"**使用方法**：{product['usage']}\n\n"
        f"**检测报告**：{product['test_reports']}\n\n"
        f"**使用场景**：{product['use_scenarios']}\n\n"
        f"**相对竞品优点**：{product['advantages']}\n\n"
        f"**临床案例**：{product['clinical_cases']}\n\n"
        f"**客户案例**：{product['client_cases']}\n"
        "</Product_Context>"
    )


def list_products() -> str:
    """返回人类可读的产品列表（用于日志/调试）"""
    lines = ["宠可灵产品清单："]
    for key, product in PETCARE_PRODUCTS.items():
        lines.append(f"  {key:35s} → {product['name']}")
    return "\n".join(lines)
